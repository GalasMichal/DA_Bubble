/**
 * CI: schreibt environment.firebase.ts aus GitHub Secrets / Env (kein environment.local.ts).
 */
const fs = require('fs');
const path = require('path');

const out = path.join(process.cwd(), 'src', 'environments', 'environment.firebase.ts');

const firebase = {
  projectId: process.env.FIREBASE_PROJECT_ID || 'da-bubble-de268',
  appId:
    process.env.FIREBASE_APP_ID ||
    '1:677473563082:web:3e599bda852f5085a15f33',
  storageBucket:
    process.env.FIREBASE_STORAGE_BUCKET || 'da-bubble-de268.appspot.com',
  apiKey: process.env.FIREBASE_API_KEY || '',
  authDomain:
    process.env.FIREBASE_AUTH_DOMAIN || 'da-bubble-de268.firebaseapp.com',
  messagingSenderId: process.env.FIREBASE_MESSAGING_SENDER_ID || '677473563082',
};

const mainChannelId =
  process.env.MAIN_CHANNEL_ID || '55dO4OXETme2oZEiCPZH';

if (!firebase.apiKey) {
  console.error(
    '[ci-env] FIREBASE_API_KEY fehlt — GitHub Secret setzen oder lokal deployen.'
  );
  process.exit(1);
}

const content = `import { AppEnvironment } from './environment.types';

/** Generated by scripts/write-ci-firebase-env.cjs — do not edit. */
export const environment: AppEnvironment = {
  production: true,
  firebase: {
    projectId: '${firebase.projectId}',
    appId: '${firebase.appId}',
    storageBucket: '${firebase.storageBucket}',
    apiKey: '${firebase.apiKey}',
    authDomain: '${firebase.authDomain}',
    messagingSenderId: '${firebase.messagingSenderId}',
  },
  mainChannelId: '${mainChannelId}',
};
`;

fs.writeFileSync(out, content);
console.log('[ci-env] wrote', path.relative(process.cwd(), out));
